import stats, re
from corpus import fmt
from stats import short, verify, GROUPS
from render_criteria import LAB, wq
def vmap(v):
    b=stats.BM[v['key']]; o=[f'### `{v["key"]}` — "{v["title"]}"\n',f'Group **{LAB[v["group"]]}** · runtime {fmt(v["dur"])} · {v["words"]} host words · {round(v["words"]/(v["dur"]/60))} WPM · {len(v["sents"])} sentences\n',
      '| % | time | beat | verbatim line |','|---:|---:|---|---|']
    for e in b['events']:
        t=short(e['text'],32).replace('|','/'); assert verify(t,v), (v['key'],t)
        o.append(f'| {e["pct"]} | {fmt(e["t"])} | {e["beat"]} | {t} |')
    o.append('\n**Decile skeleton** (first host sentence of each 10% slice — what the viewer hears as each tenth begins):\n')
    o.append('| slice | time | opening line |'); o.append('|---|---:|---|')
    for d in range(10):
        s=next((s for s in v['sents'] if s['pct']>=d*10),None)
        if s: o.append(f'| {d*10}-{d*10+10}% | {fmt(s["t"])} | {short(s["text"],28).replace("|","/")} |')
    secs=[e['pct'] for e in b['events'] if e['beat'] in ('SECTION TURN','QUESTION TURN (re-hook)')]
    sp=[v['sents'][x[0]]['pct'] for x in b['spblocks']]
    o.append(f'\n**Shape:** hook→promise at {v["sents"][b["hook_end"]]["pct"]}% ({fmt(v["sents"][b["hook_end"]]["t"])}); {len(secs)} turns at {", ".join(str(x) for x in secs)}%; sponsor at {", ".join(str(x) for x in sp) or "none"}%; conclusion at {v["sents"][b["conc"]]["pct"] if b["conc"] is not None else "not detected (ends on last section)"}%.\n')
    return '\n'.join(o)
def template(group_filter,name):
    vs=[v for v in stats.vids() if group_filter(v)]
    P=lambda f: [(x,v['weight']) for v in vs for x in [f(v,stats.BM[v['key']])] if x is not None]
    he=P(lambda v,b:v['sents'][b['hook_end']]['pct']); hs=P(lambda v,b:v['sents'][b['hook_end']]['t'])
    th=P(lambda v,b:v['sents'][b['thesis']]['pct'] if b['thesis'] is not None else None)
    sp=P(lambda v,b:v['sents'][b['spblocks'][0][0]]['pct'] if b['spblocks'] and v['sents'][b['spblocks'][0][0]]['pct']<90 else None)
    cc=P(lambda v,b:v['sents'][b['conc']]['pct'] if b['conc'] is not None else None)
    ns=P(lambda v,b:len([e for e in b['events'] if e['beat'] in ('SECTION TURN','QUESTION TURN (re-hook)')]))
    du=P(lambda v,b:v['dur']/60)
    hist=[0]*10; tw=0
    for v in vs:
        b=stats.BM[v['key']]
        for e in b['events']:
            if e['beat'] in ('SECTION TURN','QUESTION TURN (re-hook)'): hist[min(int(e['pct']//10),9)]+=v['weight']
        tw+=v['weight']
    m=lambda p,q=.5: round(wq(p,q),1) if p else None
    o=[f'### Template: {name}\n',f'Built from {len(vs)} videos ({", ".join(sorted(set(LAB[v["group"]] for v in vs)))}), weighted.\n',
       f'- Runtime: median {m(du)} min (IQR {m(du,.25)}–{m(du,.75)})',f'- Promise/roadmap lands: {m(he)}% (≈{fmt(m(hs))}; IQR {m(he,.25)}–{m(he,.75)}%)',
       f'- Thesis/stakes line: {m(th) if th else "—"}% (detected in {len(th)}/{len(vs)} videos)',f'- Sponsor (if any): {m(sp) if sp else "none"}% (IQR {m(sp,.25) if sp else "—"}–{m(sp,.75) if sp else "—"}%), present in {len(sp)}/{len(vs)}',
       f'- Conclusion begins: {m(cc) if cc else "—"}% (IQR {m(cc,.25) if cc else "—"}–{m(cc,.75) if cc else "—"}%)',f'- Major turns: median {m(ns)} per video',
       '- Weighted turn density by decile: '+' '.join(f'{i*10}%:{round(100*h/max(sum(hist),1))}' for i,h in enumerate(hist))+' (% of all turns)\n']
    n=int(round(m(ns) or 7)); a=m(he) or 4; z=m(cc) or 85
    o.append('| beat | position | job |'); o.append('|---|---:|---|')
    o.append(f'| Cold open | 0% | Concrete incident/number/scene; twist inside 30 s |')
    if th: o.append(f'| Thesis/stakes | ~{min(m(th),a)}–{max(m(th),a)}% | Why it matters to you / the world |')
    o.append(f'| Promise/roadmap | {a}% | "I want to take you…" / "let\'s break down…" |')
    for k in range(n):
        pos=round(a+(z-a)*(k+1)/(n+1),1)
        o.append(f'| Turn {k+1} | {pos}% | {"context/backstory" if k==0 else "mechanism" if k==1 else "escalation" if k<n-2 else "counter-case / skeptic pass" if k==n-2 else "zoom-out to system / future"} |')
    if sp: o.append(f'| Sponsor (bridged) | {m(sp)}% | 35-90 s, bridged from the problem, re-enter with open loop |')
    o.append(f'| Conclusion | {z}% | Synthesis + callback + agency |'); o.append('| CTA/sign-off | 97–100% | 1–3 lines |\n')
    return '\n'.join(o)
def render():
    o=['# Beat maps — every corpus video (host-only) + weighted templates\n','Generated by `build/beats.py`. Positions are % of runtime from caption timestamps. Beat labels are detector output (regex markers for promise, thesis, section turns, sponsor blocks, conclusion, CTA); treat them as a strong first pass, not ground truth. Labels: COLD OPEN / HOOK, THESIS / STAKES, PROMISE / ROADMAP, SECTION TURN, QUESTION TURN (re-hook), SPONSOR READ, RETURN FROM SPONSOR, CONCLUSION, CTA, FINAL LINE.\n',
       '## Part 1 — Weighted templates\n']
    o.append(template(lambda v:True,'BLENDED CHANNEL (all weights) — default'))
    o.append(template(lambda v:v['group']=='Adam','ADAM MODE (long investigative essay)'))
    o.append(template(lambda v:v['group']=='Gen','GEN MODE (finance/econ explainer)'))
    o.append(template(lambda v:v['group'] in ('Especially','Oil'),'MECHANISM MODE (especially + oil)'))
    o.append(template(lambda v:v['group']=='Others','OTHERS (breadth reference, 1x)'))
    o.append('\n## Part 2 — Per-video beat maps (ordered by weight)\n')
    order={'Adam':0,'Oil':1,'Gen':2,'Especially':3,'Others':4}
    for v in sorted(stats.vids(),key=lambda v:order[v['group']]): o.append(vmap(v))
    return '\n'.join(o)
